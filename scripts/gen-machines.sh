#!/usr/bin/env bash
# Regenerates ../machines.tf: one talos_machine "slot" per possible node,
# chained with depends_on so OS upgrades roll ONE node at a time.
#
# Why slots instead of for_each: instances of one resource can't depend on
# each other, so a for_each talos_machine would upgrade all nodes at once.
#
# Usage: scripts/gen-machines.sh [MAX_CP=5] [MAX_WORKERS=10]
# After raising MAX_WORKERS, also update:
#   - the workers.count validation in variables.tf
#   - talos_cluster.this depends_on in talos.tf
set -euo pipefail

max_cp=${1:-5}
max_w=${2:-10}
out="$(cd "$(dirname "$0")/.." && pwd)/machines.tf"

slot() { # $1 = resource name, $2 = list local, $3 = index, $4 = depends_on
  cat <<EOF

resource "talos_machine" "$1" {
  count      = length(local.$2) > $3 ? 1 : 0
  depends_on = [$4]

  node                            = local.nodes[local.$2[$3]].ip
  client_configuration            = talos_machine_secrets.this.client_configuration
  machine_configuration           = data.talos_machine_configuration.node[local.$2[$3]].machine_configuration
  image                           = local.talos_installer_image
  drain_on_upgrade                = true
  kubeconfig_wo                   = ephemeral.talos_cluster_kubeconfig.drain.kubeconfig_raw
  ignore_kubernetes_upgrade_drift = true
}
EOF
}

{
  cat <<EOF
# GENERATED by scripts/gen-machines.sh ($max_cp control plane + $max_w worker slots). Do not edit by hand.
#
# One talos_machine per node slot, chained with depends_on, so a talos_version
# change rolls through the cluster ONE node at a time:
#
#   cp_1 -> ... -> cp_$max_cp -> w_1 -> ... -> w_$max_w -> talos_cluster (upgrade-k8s)
#
# Per node: pull installer -> install -> cordon/drain -> reboot -> wait for the
# Kubernetes node to be Ready -> uncordon. Then the next node starts.
# Unused slots have count = 0 and are skipped.
#
# ignore_kubernetes_upgrade_drift: Kubernetes component image tags are owned by
# talos_cluster (upgrade-k8s), not by config re-apply.
EOF
  prev="proxmox_virtual_environment_vm.node"
  for i in $(seq 1 "$max_cp"); do
    slot "cp_$i" cp_names $((i - 1)) "$prev"
    prev="talos_machine.cp_$i"
  done
  for i in $(seq 1 "$max_w"); do
    slot "w_$i" worker_names $((i - 1)) "$prev"
    prev="talos_machine.w_$i"
  done
} >"$out"

echo "wrote $out"
